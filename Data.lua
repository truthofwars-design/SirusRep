local function Custom(key)
	local t = SirusRepDB and SirusRepDB.customGuides
	return t and t[key] or nil
end

function ns.GetGuide(name, group)
	if name then
		local k = ns.Lower(name)
		local c = Custom(k)
		if c then return c, false end
		local g = Guide[k]
		if g then return g, false end
	end
	if group then
		local k = ns.Lower(group)
		local c = Custom(k)
		if c then return c, true end
		local g = Guide[k]
		if g then return g, true end
	end
	return nil, false
end
